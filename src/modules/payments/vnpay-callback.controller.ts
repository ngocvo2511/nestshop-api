import { applyDecorators, Controller, Get, Header, Req } from '@nestjs/common';
import { ApiOperation, ApiResponse, ApiTags, ApiQuery } from '@nestjs/swagger';
import { ContextRequest, ResponseMode } from '../../common/http/response-mode';
import { browserReturnSchema } from './reconciliation.openapi';
import { VnpayCallbackService } from './vnpay-callback.service';
const rawQuery = (req: ContextRequest) =>
  req.originalUrl.includes('?')
    ? req.originalUrl.slice(req.originalUrl.indexOf('?') + 1)
    : '';
function CallbackQueries() {
  const fields: Array<[string, number, boolean, string?]> = [
    ['vnp_TmnCode', 8, true, 'Merchant code assigned by VNPay.'],
    [
      'vnp_TxnRef',
      100,
      true,
      'Payment reference created by this API when the payment link was generated.',
    ],
    [
      'vnp_Amount',
      12,
      true,
      'Amount in VND multiplied by 100. For example, 350000 VND is sent as 35000000. VNPay sends this as a string of digits.',
    ],
    [
      'vnp_OrderInfo',
      255,
      true,
      'Order description returned by VNPay. Keep the value unchanged.',
    ],
    [
      'vnp_ResponseCode',
      2,
      true,
      'VNPay response code. 00 indicates a successful provider response; the server still checks the other fields.',
    ],
    [
      'vnp_TransactionStatus',
      2,
      true,
      'VNPay transaction status. 00 indicates success.',
    ],
    ['vnp_TransactionNo', 15, true, 'Transaction number assigned by VNPay.'],
    [
      'vnp_SecureHash',
      128,
      true,
      'Signature generated by VNPay. The server uses it to check that the callback has not been changed. Do not generate or edit it manually.',
    ],
    [
      'vnp_PayDate',
      14,
      false,
      'Payment time in Vietnam time (UTC+7), formatted as yyyyMMddHHmmss. For example, 20261118163438 means 18 November 2026 at 16:34:38.',
    ],
    ['vnp_BankCode', 20, false, 'Bank code, such as NCB.'],
    [
      'vnp_BankTranNo',
      255,
      false,
      'Transaction reference assigned by the bank.',
    ],
    [
      'vnp_CardType',
      20,
      false,
      'Payment method or card type reported by VNPay, such as ATM.',
    ],
    ['vnp_CurrCode', 3, false, 'Currency code. Must be VND if supplied.'],
  ];
  return applyDecorators(
    ...fields.map(([name, maxLength, required, description]) =>
      ApiQuery({
        name,
        required,
        description:
          description ??
          'Value sent and signed by VNPay. Keep it unchanged and do not send duplicate fields.',
        schema: { type: 'string', maxLength },
      }),
    ),
  );
}
@Controller('payments/vnpay')
@ApiTags('VNPay callbacks')
export class VnpayCallbackController {
  constructor(private readonly callbacks: VnpayCallbackService) {}
  @Get('ipn')
  @CallbackQueries()
  @ResponseMode('provider')
  @Header('Cache-Control', 'no-store')
  @ApiOperation({
    summary: 'Receive payment confirmation from VNPay (IPN)',
    description:
      'VNPay calls this endpoint directly to report a payment result. It does not need a login token; the server checks the VNPay signature instead. Register the full public HTTPS URL with VNPay, including /api/v1/payments/vnpay/ipn. localhost cannot receive calls from VNPay.\n\nA valid, successful notification received before the deadlines can update the payment to SUCCESS and the order to PAID. Late or conflicting notifications are recorded for review without marking the order as paid. Returns RspCode and Message directly to VNPay.',
  })
  @ApiResponse({
    status: 200,
    description:
      'VNPay acknowledgement: 00 = handled, 02 = duplicate, 01 = unknown transaction or merchant, 04 = amount mismatch, 97 = invalid callback, 99 = processing error (VNPay should retry). A code of 00 does not always mean the order was marked as paid; check its stored status.',
    schema: {
      type: 'object',
      properties: {
        RspCode: { type: 'string', enum: ['00', '02', '01', '04', '97', '99'] },
        Message: { type: 'string' },
      },
    },
  })
  ipn(@Req() req: ContextRequest) {
    return this.callbacks.ipn(rawQuery(req), req.correlationId);
  }
  @Get('return')
  @CallbackQueries()
  @Header('Cache-Control', 'no-store')
  @ApiOperation({
    summary: 'Receive the customer redirect after payment',
    description:
      'VNPay redirects the customer browser here after payment. The server checks the signature and returns the payment reference and provider response code. This endpoint does not update the order or payment in the database. settlementAuthoritative=false means that the stored payment status must be confirmed separately through IPN. Use the order details API to read the latest saved status. Invalid callback data returns 400.',
  })
  @ApiResponse({
    status: 200,
    description:
      'Verified return information for display. This response does not confirm a database update.',
    schema: browserReturnSchema,
  })
  @ApiResponse({
    status: 400,
    description:
      'VALIDATION_FAILED: The callback fields or signature are invalid.',
  })
  browserReturn(@Req() req: ContextRequest) {
    return this.callbacks.browserReturn(rawQuery(req));
  }
}
